ALL_EVENT_FIELDS: list[tuple[str, pa.DataType]] = _STANDARD_FIELDS + _EXTENDED_FIELDS
EVENT_SCHEMA: pa.Schema = pa.schema([(name, dtype) for name, dtype in ALL_EVENT_FIELDS])
_TYPE_LOOKUP: dict[str, pa.DataType] = {name: dtype for name, dtype in ALL_EVENT_FIELDS}


def cast_event_row(raw: dict[str, Any]) -> dict[str, Any]:
    """Casts raw string dictionary row into typed primitives according to EVENT_SCHEMA."""
    out: dict[str, Any] = {}
    for col, val in raw.items():
        expected_type = _TYPE_LOOKUP.get(col)
        if expected_type is None:
            out[col] = val
        elif expected_type == pa.bool_():
            out[col] = parse_bool(val)
        elif pa.types.is_integer(expected_type):
            out[col] = parse_int(val)
        else:
            out[col] = str(val) if val is not None else None
    return out
